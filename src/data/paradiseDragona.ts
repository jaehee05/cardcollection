function toCard(row: Row, setId: string): PokemonCard {
  const [number, name, rarity, type, hp, stage, marketPrice] = row;
  return {
    id: `${setId}-${String(number).padStart(3, "0")}`,
    setId,
    number,
    name,
    rarity,
    type,
    hp,
    stage,
    marketPrice,
  };
}

